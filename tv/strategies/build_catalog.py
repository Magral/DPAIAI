#!/usr/bin/env python3
"""Build an auditable command-only catalog; no shell execution of source text."""
import pathlib,json,re,shlex,hashlib,socket,subprocess,time,tempfile,sys
root=pathlib.Path(__file__).resolve().parents[2]
base=["", "--split 1", "--disorder 1", "--tlsrec 1+s", "--disorder 1 --tlsrec 1+s", "--split 2", "--split 1 --tlsrec 1+s", "--timeout 8 --cache-ttl 600 --split 1 --auto torst,ssl_err --disorder 1 --auto torst,ssl_err --tlsrec 1+s --auto torst,ssl_err --disorder 1 --tlsrec 1+s"]
short=dict(s='split',d='disorder',o='oob',q='disoob',f='fake',t='ttl',O='fake-offset',n='fake-sni',Q='fake-tls-mod',e='oob-data',M='mod-http',r='tlsrec',m='tlsminor',a='udp-fake',T='timeout',A='auto',L='auto-mode',u='cache-ttl',K='proto',V='pf',R='round',b='buf-size',W='await-int')
flags=dict(S='md5sig',Y='drop-sack',F='tfo',Z='wait-send')
allowed=set(short.values())|set(flags.values())
sni=['google.com','youtube.com','googlevideo.com','ytimg.com','ggpht.com']

def normalize(line):
    line=line.strip().replace('–','--').replace('—','--').replace('\\-','-')
    line=re.sub(r'(-[sdoqfr]\S*)\s+(\+[a-z]+)',r'\1\2',line)
    line=line.replace('--tls-sni','--fake-sni')
    if line.startswith('s1 '): line='-'+line
    tokens=shlex.split(line)
    out=[];i=0
    while i<len(tokens):
        token=tokens[i];i+=1
        if token.startswith('--'):
            name,sep,value=token[2:].partition('=')
            if name not in allowed: raise ValueError('not a command-only desync option: '+name)
            if name in flags.values():
                if sep: raise ValueError('value for a flag')
                out.append('--'+name);continue
            if not sep:
                if i>=len(tokens): raise ValueError('missing argument')
                value=tokens[i];i+=1
        elif token.startswith('-') and len(token)>1:
            key=token[1]
            if key in flags:
                if len(token)!=2: raise ValueError('combined flags not supported')
                out.append('--'+flags[key]);continue
            if key not in short: raise ValueError('unknown short option '+key)
            name=short[key];value=token[2:]
            if not value:
                if i>=len(tokens):raise ValueError('missing argument')
                value=tokens[i];i+=1
        else: raise ValueError('unexpected text: '+token)
        if not re.fullmatch(r'[A-Za-z0-9_.,:+?*#=-]+',value): raise ValueError('non-argument content')
        if name=='buf-size' and not 500<=int(value)<=65536: raise ValueError('buffer outside TV bounds')
        out.extend(['--'+name,value])
    if len(out)>480 or len(' '.join(out))>4096:raise ValueError('oversized command')
    return ' '.join(out)

def starts(exe,args):
    reservation=socket.socket();reservation.bind(('127.0.0.1',0));port=reservation.getsockname()[1];reservation.close()
    proc=subprocess.Popen([str(exe),'--ip','127.0.0.1','--port',str(port),'--proto','udp','--pf','53','--auto','none',*shlex.split(args)],stdout=subprocess.DEVNULL,stderr=subprocess.PIPE)
    try:
        deadline=time.monotonic()+1
        while time.monotonic()<deadline:
            if proc.poll() is not None: return False,proc.stderr.read().decode(errors='replace').strip()[-300:]
            try:
                with socket.create_connection(('127.0.0.1',port),.1) as client:
                    client.settimeout(.3);client.sendall(b'\x05\x01\x00')
                    if client.recv(2)!=b'\x05\x00':return False,'SOCKS5 negotiation failed'
                return True,''
            except OSError:time.sleep(.005)
        return False,'startup timeout'
    finally:
        proc.terminate()
        try:proc.wait(2)
        except subprocess.TimeoutExpired:proc.kill();proc.wait()
        proc.stderr.close()

def compile_engine(exe):
    source=root/'tv/src/main/cpp/engine'
    subprocess.run(['cc','-D_DEFAULT_SOURCE','-std=c99','-O2','-I'+str(source),*[str(source/(s+'.c')) for s in ['packets','main','conev','proxy','desync','mpool','extend']],'-o',str(exe)],check=True)

def render(catalog):
    entries=catalog['strategies']
    quoted=lambda s:json.dumps(s,ensure_ascii=False).replace('$','\\$')
    parts=['package io.github.magral.dpipilot.tv\n\n// Generated by tv/strategies/build_catalog.py; sources and rejects are recorded in catalog.json.\nobject StrategyCatalog {', '    const val version = "'+catalog['version']+'"','    const val engine = "ByeDPI 17.3 / ba532298de7b"']
    for field,values in [('commands',[e['args'] for e in entries]),('ids',[e['id'] for e in entries]),('origins',[', '.join(e['sources']) for e in entries])]:
        groups=[values[i:i+80] for i in range(0,len(values),80)]
        parts.append('    val '+field+' = '+(' + '.join(field+str(i)+'()' for i in range(len(groups)))))
        for i,group in enumerate(groups):parts.append('    private fun '+field+str(i)+'() = listOf(\n'+',\n'.join('        '+quoted(v) for v in group)+'\n    )')
    parts.append('    val sources = listOf(\n'+',\n'.join('        '+quoted(s['id']+': '+s['title']+'\n'+s['url']) for s in catalog['sources'])+'\n    )')
    parts.append('}')
    return '\n'.join(parts)+'\n'

def main():
    catalog_path=root/'tv/strategies/catalog.json';kotlin=root/'tv/src/main/java/io/github/magral/dpipilot/tv/StrategyCatalog.kt'
    if '--check' in sys.argv:
        catalog=json.loads(catalog_path.read_text())
        assert kotlin.read_text()==render(catalog),'Generated Kotlin differs from catalog'
        assert len({s['id'] for s in catalog['strategies']})==len(catalog['strategies'])
        with tempfile.TemporaryDirectory() as tmp:
            exe=pathlib.Path(tmp)/'engine';compile_engine(exe)
            for entry in catalog['strategies']:
                ok,error=starts(exe,entry['args']);assert ok,(entry['id'],error)
        print(f"{len(catalog['strategies'])} unique catalog strategies started and negotiated SOCKS5 with pinned native engine")
        return
    sources=json.loads((root/'tv/strategies/sources.json').read_text())
    entries=[];keys={};rejects=[]
    for n,args in enumerate(base):
        key=normalize(args);keys[key]=len(entries)
        entries.append(dict(id=hashlib.sha256(key.encode()).hexdigest()[:16],args=args,sources=['pilot-original'],legacy=n))
    with tempfile.TemporaryDirectory() as tmp:
        exe=pathlib.Path(tmp)/'engine';compile_engine(exe)
        for source in sources:
            for raw in source['commands']:
                variants=[raw.replace('{sni}',domain) for domain in sni] if '{sni}' in raw else [raw]
                for candidate in variants:
                    try:key=normalize(candidate)
                    except (ValueError,TypeError) as err:
                        rejects.append(dict(source=source['id'],raw=candidate,reason=str(err)));continue
                    if key in keys:
                        e=entries[keys[key]]
                        if source['id'] not in e['sources']:e['sources'].append(source['id'])
                        continue
                    ok,error=starts(exe,key)
                    if not ok:
                        rejects.append(dict(source=source['id'],raw=candidate,reason='native: '+error));continue
                    keys[key]=len(entries)
                    entries.append(dict(id=hashlib.sha256(key.encode()).hexdigest()[:16],args=key,sources=[source['id']]))
    catalog=dict(version='2026-10-31.1',engine_commit='ba532298de7b28cfe854aea83d061369d13ca290',strategies=entries,rejected=rejects,sources=[{k:v for k,v in s.items() if k!='commands'} for s in sources],notes=['Startup/SOCKS acceptance is not ISP effectiveness.','Five fake-SNI substitutions use the service-domain list documented by NetFix; not five independently reported successes.','Aliases, typography and detached offset suffixes normalized; unrelated operations and external-file arguments excluded.'])
    catalog_path.write_text(json.dumps(catalog,ensure_ascii=False,indent=2)+'\n')
    kotlin.write_text(render(catalog))
    print(json.dumps(dict(accepted=len(entries),rejected=len(rejects),source_counts={s['id']:sum(s['id'] in e['sources'] for e in entries) for s in sources}),ensure_ascii=False))
if __name__=='__main__':main()
